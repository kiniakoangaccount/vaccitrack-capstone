create type public.user_role as enum ('admin', 'veterinarian', 'bhw', 'client', 'viewer');
create type public.animal_species as enum ('Dog', 'Cat');
create type public.animal_classification as enum ('Pet', 'Stray');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role public.user_role not null default 'client',
  created_at timestamptz not null default now()
);

create table public.puroks (
  id bigint generated by default as identity primary key,
  name text not null unique,
  latitude numeric(10, 7) not null,
  longitude numeric(10, 7) not null,
  created_at timestamptz not null default now()
);

create table public.animals (
  id bigint generated by default as identity primary key,
  name text not null,
  species public.animal_species not null default 'Dog',
  classification public.animal_classification not null default 'Pet',
  owner_name text not null,
  purok_id bigint not null references public.puroks(id),
  breed text,
  age integer not null default 0 check (age >= 0),
  sex text,
  vaccinated boolean not null default false,
  vaccine_date date,
  next_due_date date,
  color text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint animals_vaccine_date_required check (vaccinated = false or vaccine_date is not null),
  constraint animals_next_due_after_vaccine check (next_due_date is null or vaccine_date is null or next_due_date >= vaccine_date)
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger animals_set_updated_at
before update on public.animals
for each row execute function public.set_updated_at();

alter table public.profiles enable row level security;
alter table public.puroks enable row level security;
alter table public.animals enable row level security;

create policy "Users can read their own profile"
  on public.profiles for select to authenticated using (id = auth.uid());
create policy "Authenticated users can read puroks"
  on public.puroks for select to authenticated using (true);
create policy "Staff can read animals"
  on public.animals for select to authenticated
  using (exists (select 1 from public.profiles where id = auth.uid() and role in ('admin', 'veterinarian', 'bhw')));
create policy "Staff can add animals"
  on public.animals for insert to authenticated
  with check (exists (select 1 from public.profiles where id = auth.uid() and role in ('admin', 'veterinarian', 'bhw')));
create policy "Staff can update animals"
  on public.animals for update to authenticated
  using (exists (select 1 from public.profiles where id = auth.uid() and role in ('admin', 'veterinarian', 'bhw')));

