create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role, username, contact_number, id_document_reference, status)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(coalesce(new.email, 'VacciTrack user'), '@', 1)),
    'client',
    nullif(new.raw_user_meta_data ->> 'username', ''),
    nullif(new.raw_user_meta_data ->> 'contact_number', ''),
    nullif(new.raw_user_meta_data ->> 'id_document_reference', ''),
    'pending'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

