-- Auto-generate notifications when an animal becomes overdue
create or replace function public.notify_overdue_vaccines()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  v_owner uuid;
  v_name text;
  v_due date;
begin
  for v_owner, v_name, v_due in
    select user_id, name, next_due_date
    from public.animals
    where next_due_date is not null
      and next_due_date < current_date
      and user_id is not null
  loop
    insert into public.notifications (user_id, title, message, type, dedupe_key)
    values (
      v_owner,
      'Vaccination overdue',
      format('%s''s vaccination was due on %s. Please schedule a follow-up.', v_name, to_char(v_due, 'Mon DD, YYYY')),
      'danger',
      format('overdue:%s:%s', v_owner, v_due)
    )
    on conflict do nothing;
  end loop;
  return new;
end;
$$;

