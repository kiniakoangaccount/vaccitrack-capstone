create type public.user_role as enum ('admin', 'veterinarian', 'bhw', 'client', 'viewer');
create type public.animal_species as enum ('Dog', 'Cat');
create type public.animal_classification as enum ('Pet', 'Stray');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role public.user_role not null default 'client',
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)), 'client');
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create table public.puroks (
  id bigint generated by default as identity primary key,
  name text not null unique,
  latitude numeric(10, 7) not null,
  longitude numeric(10, 7) not null,
  created_at timestamptz not null default now()
);

create table public.animals (
  id bigint generated by default as identity primary key,
  name text not null,
  species public.animal_species not null default 'Dog',
  classification public.animal_classification not null default 'Pet',
  owner_name text not null,
  user_id uuid references auth.users(id) on delete set null,
  purok_id bigint not null references public.puroks(id),
  breed text,
  age integer not null default 0 check (age >= 0),
  sex text,
  vaccinated boolean not null default false,
  vaccine_date date,
  next_due_date date,
  vaccine_type text,
  latitude numeric(10, 7),
  longitude numeric(10, 7),
  color text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint animals_vaccine_date_required check (vaccinated = false or vaccine_date is not null),
  constraint animals_next_due_after_vaccine check (next_due_date is null or vaccine_date is null or next_due_date >= vaccine_date)
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger animals_set_updated_at
before update on public.animals
for each row execute function public.set_updated_at();

create table public.breeds (
  id bigint generated by default as identity primary key,
  name text not null,
  species public.animal_species not null default 'Dog',
  created_at timestamptz not null default now(),
  unique (name, species)
);

create table public.vaccines (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

create table public.vaccination_history (
  id bigint generated by default as identity primary key,
  animal_id bigint not null references public.animals(id) on delete cascade,
  vaccine_date date not null,
  next_due_date date,
  vaccine_type text,
  administered_by text,
  notes text,
  recorded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.feedback (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  name text,
  contact text,
  category text not null default 'Suggestion' check (category in ('Bug Report', 'Suggestion', 'Complaint', 'Compliment', 'Other')),
  message text not null,
  status text not null default 'New' check (status in ('New', 'Reviewed', 'Resolved')),
  admin_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.audit_log (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  action text not null check (action in ('INSERT', 'UPDATE', 'DELETE', 'SMS_SENT', 'SMS_ATTEMPT')),
  table_name text not null,
  record_id bigint,
  notes text,
  created_at timestamptz not null default now()
);

