create or replace function public.validate_animal_dates()
returns trigger
language plpgsql
as $$
begin
  if new.vaccine_date > current_date then
    raise exception 'Vaccination date cannot be in the future';
  end if;
  if new.next_due_date is not null and new.vaccine_date is not null and new.next_due_date < new.vaccine_date then
    raise exception 'Next due date must be on or after vaccine date';
  end if;
  return new;
end;
$$;

drop trigger if exists animals_validate_dates on public.animals;
